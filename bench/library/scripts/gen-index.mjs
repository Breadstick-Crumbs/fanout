// Generates src/index.mjs: re-exports every module in src/. Run `npm run gen` after adding a module.
import { readdirSync, writeFileSync } from "node:fs";
const mods = readdirSync("src").filter((f) => f.endsWith(".mjs") && f !== "index.mjs").sort();
writeFileSync("src/index.mjs", "// GENERATED by scripts/gen-index.mjs. Do not edit.\n" + mods.map((m) => `export * from "./${m}";`).join("\n") + "\n");
